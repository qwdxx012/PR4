p = float(input("Начальный объем древесины p (куб. м): "))
k = float(input("Ежегодный прирост k (%): "))
t = float(input("Годовой план заготовки t (куб. м): "))

if p * k / 100 >= t:
    print("Прирост не меньше заготовки, лес никогда не закончится")
else:
    years = 0
    while p > 0:
        p = p + p * k / 100 - t
        years = years + 1
    print("Лес закончится, количество лет:", years)
